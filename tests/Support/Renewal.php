<?php

declare(strict_types=1);

namespace Gunner42\LaravelEetModule\Tests\Support;

use Carbon\CarbonImmutable;
use Gunner42\LaravelEetModule\Enums\Environment;
use Gunner42\LaravelEetModule\Enums\RenewalProblem;
use Gunner42\LaravelEetModule\Enums\RenewalStatus;
use Gunner42\LaravelEetModule\Events\CertificateRenewalFailed;
use Gunner42\LaravelEetModule\Events\CertificateRenewed;
use Gunner42\LaravelEetModule\Facades\Eet;
use Gunner42\LaravelEetModule\Models\CashRegister;
use Gunner42\LaravelEetModule\Models\CashRegisterCertificate;
use Gunner42\LaravelEetModule\Models\CertificateRenewal;
use Gunner42\LaravelEetModule\Models\Taxpayer;
use Illuminate\Encryption\Encrypter;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Event;
use RuntimeException;

/**
 * Helpers for the certificate renewal tests (spec/12). Fixtures are in
 * tests/fixtures/renewal (generated by tests/fixtures/generate-renewal.sh).
 *
 * This is test support code, not package code.
 */
final class Renewal
{
    public static function now(): CarbonImmutable
    {
        return CarbonImmutable::parse(CaEetApi::NOW);
    }

    public static function taxpayer(string $eic = 'CZ00000019'): Taxpayer
    {
        $existing = Taxpayer::query()->where('eic', $eic)->first();

        return $existing instanceof Taxpayer ? $existing : Eet::createTaxpayer($eic, 'Test '.$eic, Environment::Production);
    }

    /**
     * Imports a renewed (production) certificate fixture for the taxpayer.
     */
    public static function certificate(string $fixture = CaEetApi::RENEWED, string $eic = 'CZ00000019'): CashRegisterCertificate
    {
        return Eet::importCertificate(self::taxpayer($eic), Fixtures::read($fixture));
    }

    public static function cashRegister(string $identifier, ?CashRegisterCertificate $certificate = null, string $eic = 'CZ00000019', int $unit = 181): CashRegister
    {
        $taxpayer = self::taxpayer($eic);
        $registrationUnit = $taxpayer->registrationUnits()->where('number', $unit)->first()
            ?? Eet::createRegistrationUnit($taxpayer, $unit);

        return Eet::createCashRegister($registrationUnit, $identifier, null, $certificate);
    }

    public static function fresh(CashRegisterCertificate $certificate): CashRegisterCertificate
    {
        return CashRegisterCertificate::query()->findOrFail($certificate->getKey());
    }

    public static function latest(CashRegisterCertificate $certificate): CertificateRenewal
    {
        $renewal = CertificateRenewal::query()
            ->where('certificate_id', $certificate->getKey())
            ->orderByDesc('id')
            ->first();

        if (! $renewal instanceof CertificateRenewal) {
            throw new RuntimeException('The certificate has no renewal.');
        }

        return $renewal;
    }

    public static function renewalCount(): int
    {
        return CertificateRenewal::query()->count();
    }

    /**
     * Stores a renewal directly in a state, as left behind by an earlier run
     * (columns of the public contract, spec/10 chap. 6).
     */
    public static function insert(
        CashRegisterCertificate $certificate,
        RenewalStatus $status,
        ?string $requestId = CaEetApi::REQ_ID,
        ?RenewalProblem $problem = null,
        ?string $problemDetail = null,
        ?CashRegisterCertificate $successor = null,
    ): CertificateRenewal {
        $now = CarbonImmutable::now();
        $id = DB::table('eet_certificate_renewals')->insertGetId([
            'certificate_id' => $certificate->getKey(),
            'successor_id' => $successor?->getKey(),
            'request_id' => $requestId,
            'status' => $status->value,
            'problem' => $problem?->value,
            'problem_detail' => $problemDetail,
            'acknowledged_at' => null,
            'completed_at' => $status === RenewalStatus::Completed ? $now : null,
            'failed_at' => $status === RenewalStatus::Failed ? $now : null,
            'created_at' => $now,
            'updated_at' => $now,
        ]);

        return CertificateRenewal::query()->findOrFail($id);
    }

    /**
     * Re-encrypts the stored key with another APP_KEY, as after a key
     * rotation without APP_PREVIOUS_KEYS (R69).
     */
    public static function makeUnusable(CashRegisterCertificate $certificate, string $fixture = CaEetApi::RENEWED): void
    {
        $foreign = new Encrypter(base64_decode('b3RoZXItYXBwLWtleS1mb3ItZWV0LW1vZHVsZS0zMmI='), 'aes-256-cbc');
        $key = openssl_pkey_get_private(Fixtures::read($fixture));

        if ($key === false || ! openssl_pkey_export($key, $pem)) {
            throw new RuntimeException("Fixture [{$fixture}] contains no private key.");
        }

        DB::table('eet_cash_register_certificates')
            ->where('id', $certificate->getKey())
            ->update(['private_key' => $foreign->encryptString((string) $pem)]);
    }

    /**
     * Fakes only the renewal events, so Eloquent events keep working.
     */
    public static function fakeEvents(): void
    {
        Event::fake([CertificateRenewed::class, CertificateRenewalFailed::class]);
    }

    /**
     * The certificate stored for the taxpayer with the fingerprint of a
     * successor fixture, or null.
     */
    public static function stored(string $fixture = CaEetApi::SUCCESSOR): ?CashRegisterCertificate
    {
        return CashRegisterCertificate::query()
            ->whereRaw('lower(fingerprint_sha256) = ?', [CaEetApi::fingerprintOf($fixture)])
            ->first();
    }

    /**
     * All rows of the package tables as one JSON string.
     */
    public static function databaseDump(): string
    {
        $dump = [];

        foreach (['eet_taxpayers', 'eet_registration_units', 'eet_cash_registers', 'eet_cash_register_certificates', 'eet_certificate_renewals', 'eet_sales', 'eet_submission_attempts'] as $table) {
            $dump[$table] = DB::table($table)->get()->all();
        }

        return json_encode($dump, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
    }
}
